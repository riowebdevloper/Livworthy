/**
 * Backward compatibility alias for existing Tier 2 UI components
 */
export const TIER_2_LOCALE_METADATA: Record<string, LocaleConfig> = Object.fromEntries(
  Object.entries(SUPPORTED_LOCALES).filter(([_, cfg]) => cfg.tier === 2)
);

export const DEFAULT_LOCALE: SupportedLocale = 'en';

export function isSupportedLocale(code: string): code is SupportedLocale {
  return code in SUPPORTED_LOCALES;
}

export function isRtlLocale(locale: string): boolean {
  return SUPPORTED_LOCALES[locale]?.dir === 'rtl';
}

export function getLocaleConfig(locale: string): LocaleConfig {
  return SUPPORTED_LOCALES[locale] || SUPPORTED_LOCALES.en;
}

export function getRegisteredLocales(): LocaleConfig[] {
  return Object.values(SUPPORTED_LOCALES);
}

export function getPublishedLocales(): LocaleConfig[] {
  return Object.values(SUPPORTED_LOCALES).filter(
    (cfg) => cfg.lifecycleStatus === 'PUBLISHED' || cfg.lifecycleStatus === 'INDEXABLE'
  );
}

export function getIndexableLocales(): LocaleConfig[] {
  return Object.values(SUPPORTED_LOCALES).filter(
    (cfg) => cfg.lifecycleStatus === 'INDEXABLE' && cfg.isIndexable
  );
}
