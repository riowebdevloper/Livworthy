export function getLocalizedCountry(countryId: string, locale: string): LocalizedCountryContent | null {
  const normalizedCountry = countryId.toUpperCase();
  const countryDict = LOCALIZED_COUNTRIES[normalizedCountry];
  if (!countryDict) return null;
  return countryDict[locale] || countryDict.en || null;
}
